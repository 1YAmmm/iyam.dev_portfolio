// Map icon type string → component
export function ProjectIcon({ type, color, size = 22 }) {
  const props = { size, color }
  switch (type) {
    case 'book':    return <IconBook {...props} />
    case 'table':   return <IconTable {...props} />
    case 'check':   return <IconCheck {...props} />
    case 'layers':  return <IconLayers {...props} />
    case 'monitor': return <IconMonitor {...props} />
    case 'mobile':  return <IconMobile {...props} />
    default:        return <IconMonitor {...props} />
  }
}
